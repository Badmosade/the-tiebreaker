import React, { useState } from 'react';
import { X, Copy, Check, Download, Printer, FileText } from 'lucide-react';
import { DecisionRecord } from '../types/decision';

interface ExportModalProps {
  isOpen: boolean;
  onClose: () => void;
  decision: DecisionRecord;
}

export const ExportModal: React.FC<ExportModalProps> = ({
  isOpen,
  onClose,
  decision,
}) => {
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  const generateMarkdown = (): string => {
    let md = `# The Tiebreaker: Decision Briefing\n\n`;
    md += `**Dilemma:** ${decision.title}\n`;
    md += `**Date:** ${new Date(decision.createdAt).toLocaleDateString()}\n`;
    md += `**Status:** ${decision.status === 'resolved' ? 'Resolved' : 'In Progress'}\n\n`;

    if (decision.context) {
      md += `**Context:**\n${decision.context}\n\n`;
    }

    md += `---\n\n`;
    md += `## 🏆 The Tiebreaker Verdict\n\n`;
    md += `**Recommended Option:** ${decision.verdict.recommendedOptionName} (${decision.verdict.confidencePercent}% Confidence)\n\n`;
    md += `**Analysis:**\n${decision.verdict.tiebreakerReasoning}\n\n`;
    md += `**Crux Question:**\n> "${decision.verdict.theCruxQuestion}"\n\n`;

    md += `## ⚖️ Pros & Cons Summary\n\n`;
    decision.options.forEach((opt) => {
      md += `### ${opt.name} (${opt.tagline})\n\n`;
      md += `**Pros:**\n`;
      opt.pros.forEach((p) => {
        md += `- [${p.impact.toUpperCase()}] ${p.point} (${p.category})\n`;
      });
      md += `\n**Cons & Mitigations:**\n`;
      opt.cons.forEach((c) => {
        md += `- [${c.impact.toUpperCase()}] ${c.point} (${c.category})\n`;
        if (c.mitigation) {
          md += `  ↳ Mitigation: ${c.mitigation}\n`;
        }
      });
      md += `\n`;
    });

    md += `---\n\n`;
    md += `## 🧭 SWOT Summary\n\n`;
    decision.options.forEach((opt) => {
      md += `### ${opt.name} SWOT:\n`;
      md += `- **Strengths:** ${opt.swot.strengths.join(', ')}\n`;
      md += `- **Weaknesses:** ${opt.swot.weaknesses.join(', ')}\n`;
      md += `- **Opportunities:** ${opt.swot.opportunities.join(', ')}\n`;
      md += `- **Threats:** ${opt.swot.threats.join(', ')}\n\n`;
    });

    md += `---\n*Generated by The Tiebreaker*`;
    return md;
  };

  const markdownContent = generateMarkdown();

  const handleCopy = async () => {
    try {
      await navigator.clipboard.writeText(markdownContent);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch (err) {
      console.error('Failed to copy', err);
    }
  };

  const handleDownloadMarkdown = () => {
    const blob = new Blob([markdownContent], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `tiebreaker-${decision.id}.md`;
    link.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/40 backdrop-blur-xs animate-in fade-in duration-200">
      <div className="bg-white border border-slate-200 rounded-3xl p-6 sm:p-7 max-w-2xl w-full shadow-2xl relative flex flex-col max-h-[90vh]">
        {/* Header */}
        <div className="flex items-center justify-between pb-4 mb-4 border-b border-slate-100">
          <div className="flex items-center gap-2">
            <FileText className="w-5 h-5 text-blue-600" />
            <h3 className="font-heading font-bold text-lg text-slate-900">
              Export Decision Summary
            </h3>
          </div>
          <button
            onClick={onClose}
            className="p-1.5 rounded-lg text-slate-400 hover:text-slate-700 bg-slate-100 transition"
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        {/* Preview */}
        <div className="flex-1 overflow-y-auto bg-slate-50 p-4 rounded-xl border border-slate-200 text-xs font-mono text-slate-800 whitespace-pre-wrap leading-relaxed select-all">
          {markdownContent}
        </div>

        {/* Actions */}
        <div className="flex flex-wrap items-center justify-between gap-2.5 pt-4 mt-4 border-t border-slate-100">
          <div className="flex items-center gap-2">
            <button
              onClick={handleCopy}
              className="inline-flex items-center gap-1.5 px-3.5 py-2 rounded-xl text-xs font-semibold bg-blue-600 hover:bg-blue-700 text-white transition cursor-pointer"
            >
              {copied ? (
                <>
                  <Check className="w-4 h-4 stroke-[2.5]" />
                  <span>Copied!</span>
                </>
              ) : (
                <>
                  <Copy className="w-4 h-4" />
                  <span>Copy Text</span>
                </>
              )}
            </button>

            <button
              onClick={handleDownloadMarkdown}
              className="inline-flex items-center gap-1.5 px-3.5 py-2 rounded-xl text-xs font-medium bg-slate-100 hover:bg-slate-200 text-slate-700 border border-slate-200 transition"
            >
              <Download className="w-4 h-4 text-slate-500" />
              <span>Download .md</span>
            </button>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={() => window.print()}
              className="inline-flex items-center gap-1.5 px-3 py-2 rounded-xl text-xs font-medium text-slate-600 hover:text-slate-900 transition"
            >
              <Printer className="w-4 h-4" />
              <span>Print</span>
            </button>

            <button
              onClick={onClose}
              className="px-3.5 py-2 rounded-xl text-xs font-medium text-slate-500 hover:text-slate-800 transition"
            >
              Close
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
